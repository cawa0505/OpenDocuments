const dictionaries: Record<Locale, Dictionary> = {
  en,
  ko,
  'zh-TW': zhTW,
}

export function detectLocale(): Locale {
  if (typeof navigator !== 'undefined') {
    const lang = navigator.language.toLowerCase()
    if (lang.startsWith('zh')) return 'zh-TW'
    if (lang.startsWith('ko')) return 'ko'
  }
  return 'en'
}

export function normalizeLocale(locale: string | null | undefined): Locale {
  if (!locale) return 'en'
  if (locale === 'ko') return 'ko'
  if (locale === 'zh-TW' || locale.startsWith('zh')) return 'zh-TW'
  return 'en'
}

export function translate(locale: Locale, key: string, values?: Record<string, string | number>): string {
  let template = dictionaries[locale]?.[key] || dictionaries.en[key]

  if (!template && key) {
    // Case-insensitive & camelCase safety fallback
    const altKeys = [
      key.toLowerCase(),
      key.charAt(0).toLowerCase() + key.slice(1),
      key.charAt(0).toUpperCase() + key.slice(1)
    ]
    for (const alt of altKeys) {
      if (alt === key) continue
      const match = dictionaries[locale]?.[alt] || dictionaries.en[alt]
      if (match) {
        template = match
        break
      }
    }
  }

  template = template || key

  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (_, token: string) => String(values[token] ?? `{${token}}`))
}
